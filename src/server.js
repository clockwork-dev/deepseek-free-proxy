const http = require('http');
const path = require('path');
const readline = require('readline');
const { spawnSync } = require('child_process');

const ROOT_DIR = path.resolve(__dirname, '..');
if (require.main === module) {
    require('../lib/env').loadDotEnv(path.join(ROOT_DIR, '.env'));
}

const {
    PORT,
    HOST,
    PROXY_API_KEY,
    requireProxyApiKey,
    isTruthy,
    isProxyAuthorized,
    isLoopbackHost,
    normalizeOrigin,
    isBrowserOriginAllowed,
    setCorsResponseHeaders,
} = require('./utils/auth');

const {
    accounts,
    DS_CONFIG_PATH,
    hasAuthConfig,
    loadDeepSeekConfig,
} = require('./accounts/pool');

const {
    SUPPORTED_MODEL_IDS,
    MODEL_CONFIGS,
    ALL_MODEL_CAPABILITIES,
} = require('./deepseek/client');

const {
    sweepIdleSessions,
} = require('./sessions/manager');

const { dispatchRoute } = require('./routes/index');

let inFlight = 0;  // concurrent in-flight completions (backpressure cap)

const server = http.createServer(async (req, res) => {
    const requestOrigin = req.headers.origin;
    res.setHeader('Vary', 'Origin');
    if (!isBrowserOriginAllowed(requestOrigin)) {
        res.writeHead(403, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: { message: 'Browser origin is not allowed', type: 'cors_error' } }));
        return;
    }
    if (requestOrigin) res.setHeader('Access-Control-Allow-Origin', normalizeOrigin(requestOrigin));
    setCorsResponseHeaders(res);
    if (req.method === 'OPTIONS') { res.writeHead(204); res.end(); return; }

    let url;
    try {
        url = new URL(req.url || '/', 'http://localhost');
    } catch {
        res.writeHead(400, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: { message: 'Malformed request URL', type: 'invalid_request_error' } }));
        return;
    }
    const isPublicProbe = req.method === 'GET' && (url.pathname === '/' || url.pathname === '/health' || url.pathname === '/readyz');
    if (!isPublicProbe && !isProxyAuthorized(req.headers.authorization, PROXY_API_KEY, req.headers['x-api-key'])) {
        res.writeHead(401, {
            'Content-Type': 'application/json',
            'WWW-Authenticate': 'Bearer',
        });
        res.end(JSON.stringify({ error: { message: 'Invalid or missing proxy API key', type: 'authentication_error' } }));
        return;
    }

    const state = {
        get inFlight() { return inFlight; },
        incrementInFlight() { inFlight++; },
        decrementInFlight() { inFlight--; },
    };

    dispatchRoute(req, res, url, state);
});

